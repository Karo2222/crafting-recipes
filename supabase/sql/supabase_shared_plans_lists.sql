create or replace function public.set_shopping_list_member(
  p_shopping_list_id bigint,
  p_member_account_id bigint,
  p_permission text,
  p_remove boolean default false
)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_account_id bigint := public.current_account_id();
  v_now timestamp with time zone := now();
begin
  if v_account_id is null or p_member_account_id = v_account_id then
    raise exception 'invalid_shopping_list_member';
  end if;
  if p_permission not in ('viewer', 'editor') then
    raise exception 'invalid_shopping_list_permission';
  end if;
  if not exists (
    select 1 from public.account_friend
    where first_account_id = least(v_account_id, p_member_account_id)
      and second_account_id = greatest(v_account_id, p_member_account_id)
      and status = 'accepted'
      and deleted_at is null
  ) then
    raise exception 'accepted_friend_required';
  end if;
  if not exists (
    select 1 from public.shopping_list
    where id = p_shopping_list_id
      and account_id = v_account_id
      and deleted_at is null
  ) then
    raise exception 'shopping_list_owner_required';
  end if;

  if p_remove then
    update public.shopping_list_member
    set updated_at = v_now,
        updated_by = v_account_id,
        deleted_at = v_now,
        deleted_by = v_account_id
    where shopping_list_id = p_shopping_list_id
      and account_id = p_member_account_id;
    return;
  end if;

  insert into public.shopping_list_member as member (
    shopping_list_id, account_id, permission, status,
    created_at, created_by, updated_at, updated_by, deleted_at, deleted_by
  ) values (
    p_shopping_list_id, p_member_account_id, p_permission, 'pending',
    v_now, v_account_id, v_now, v_account_id, null, null
  )
  on conflict (shopping_list_id, account_id) do update
  set permission = excluded.permission,
      status = case
        when member.deleted_at is null and member.status = 'accepted'
          then 'accepted'
        else 'pending'
      end,
      updated_at = excluded.updated_at,
      updated_by = excluded.updated_by,
      deleted_at = null,
      deleted_by = null;
end
$$;

