create or replace function public.remove_friend(p_friend_account_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_account_id bigint := public.current_account_id();
  v_now timestamp with time zone := now();
begin
  if v_account_id is null then return; end if;
  update public.account_friend
  set updated_at = v_now,
      updated_by = v_account_id,
      deleted_at = v_now,
      deleted_by = v_account_id
  where first_account_id = least(v_account_id, p_friend_account_id)
    and second_account_id = greatest(v_account_id, p_friend_account_id)
    and deleted_at is null;

  update public.shopping_list_member as member
  set updated_at = v_now,
      updated_by = v_account_id,
      deleted_at = v_now,
      deleted_by = v_account_id
  from public.shopping_list as list
  where member.shopping_list_id = list.id
    and member.deleted_at is null
    and (
      (list.account_id = v_account_id
        and member.account_id = p_friend_account_id)
      or (list.account_id = p_friend_account_id
        and member.account_id = v_account_id)
    );

  update public.meal_plan_member as member
  set updated_at = v_now,
      updated_by = v_account_id,
      deleted_at = v_now,
      deleted_by = v_account_id
  from public.meal_plan as plan
  where member.meal_plan_id = plan.id
    and member.deleted_at is null
    and (
      (plan.account_id = v_account_id
        and member.account_id = p_friend_account_id)
      or (plan.account_id = p_friend_account_id
        and member.account_id = v_account_id)
    );
end
$$;

