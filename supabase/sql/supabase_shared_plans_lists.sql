create or replace function public.send_friend_request(p_friend_account_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare
  v_account_id bigint := public.current_account_id();
  v_first bigint;
  v_second bigint;
  v_now timestamp with time zone := now();
begin
  if v_account_id is null or p_friend_account_id = v_account_id then
    raise exception 'invalid_friend_account';
  end if;
  if not exists (
    select 1 from public.account
    where id = p_friend_account_id and deleted_at is null
  ) then
    raise exception 'friend_account_not_found';
  end if;
  v_first := least(v_account_id, p_friend_account_id);
  v_second := greatest(v_account_id, p_friend_account_id);
  insert into public.account_friend as friendship (
    first_account_id, second_account_id, requested_by, status,
    created_at, created_by, updated_at, updated_by, deleted_at, deleted_by
  ) values (
    v_first, v_second, v_account_id, 'pending',
    v_now, v_account_id, v_now, v_account_id, null, null
  )
  on conflict (first_account_id, second_account_id) do update
  set requested_by = excluded.requested_by,
      status = 'pending',
      updated_at = excluded.updated_at,
      updated_by = excluded.updated_by,
      deleted_at = null,
      deleted_by = null
  where friendship.deleted_at is not null
     or friendship.status = 'declined';
end
$$;

create or replace function public.respond_friend_request(
