create or replace function public.can_discover_shopping_list(p_list_id bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.shopping_list as list
    where list.id = p_list_id
      and list.deleted_at is null
      and (
        list.account_id = public.current_account_id()
        or exists (
          select 1 from public.shopping_list_member as member
          where member.shopping_list_id = list.id
            and member.account_id = public.current_account_id()
            and member.status in ('pending', 'accepted')
            and member.deleted_at is null
        )
      )
  )
$$;

